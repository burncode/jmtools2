import type { AppSettings, CharacterTraitDictionaryEntry } from "@/lib/tauri/commands";

function createTraitEntry(
  id: string,
  label: string,
  category: CharacterTraitDictionaryEntry["category"],
  prompt: string,
  entityTypes: CharacterTraitDictionaryEntry["entityTypes"],
  colors?: string[],
): CharacterTraitDictionaryEntry {
  return {
    category,
    colors,
    description: "",
    enabled: true,
    entityTypes,
    id,
    label,
    prompt,
    value: label,
  };
}

